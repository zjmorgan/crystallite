import numpy as np
import spglib

from crystallite.backend import xp

_INVERSION = -np.eye(3)


def _rotation(axis, degrees):
    """Proper rotation matrix by `degrees` about `axis` (Rodrigues formula)."""
    n = np.asarray(axis, dtype=float)
    n = n / np.linalg.norm(n)
    theta = np.radians(degrees)
    k = np.array(
        [[0, -n[2], n[1]], [n[2], 0, -n[0]], [-n[1], n[0], 0]]
    )
    return np.eye(3) + np.sin(theta) * k + (1 - np.cos(theta)) * (k @ k)


def _mirror(normal):
    """Reflection matrix through the plane with the given normal."""
    n = np.asarray(normal, dtype=float)
    n = n / np.linalg.norm(n)
    return np.eye(3) - 2 * np.outer(n, n)


_X, _Y, _Z = (1, 0, 0), (0, 1, 0), (0, 0, 1)
_DIAG3 = (1, 1, 1)
_DIAG2 = (1, 1, 0)


def _close_group(generators, tol=1e-6):
    """Full set of operations generated by `generators` under composition."""
    ops = [np.eye(3)]

    def add(candidate):
        for op in ops:
            if np.allclose(op, candidate, atol=tol):
                return False
        ops.append(candidate)
        return True

    for g in generators:
        add(np.asarray(g, dtype=float))

    changed = True
    while changed:
        changed = False
        for a in list(ops):
            for b in list(ops):
                if add(a @ b):
                    changed = True

    return np.stack(ops, axis=0)


_C2X, _C2Y, _C2Z = _rotation(_X, 180), _rotation(_Y, 180), _rotation(_Z, 180)
_C3Z, _C4Z, _C6Z = _rotation(_Z, 120), _rotation(_Z, 90), _rotation(_Z, 60)
_C3_111 = _rotation(_DIAG3, 120)
_MX, _MY, _MZ = _mirror(_X), _mirror(_Y), _mirror(_Z)
_S4Z, _S6Z = -_rotation(_Z, 90), -_rotation(_Z, 60)

