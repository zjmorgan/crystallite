_operations_cache = {}


def point_group_operations(point_group):
    """(n, 3, 3) Cartesian rotation/reflection matrices for `point_group`.

    `n` is the group order. Standard setting: principal axis along z,
    secondary two-fold/mirror along x, monoclinic unique axis along y,
    cubic tertiary axis along [111].
    """
    if point_group not in _GENERATORS:
        raise ValueError(f"unrecognized point group: {point_group!r}")

    if point_group not in _operations_cache:
        ops = _close_group(_GENERATORS[point_group])
        expected = _EXPECTED_ORDER[point_group]
        if len(ops) != expected:
            raise RuntimeError(
                f"point group {point_group!r}: generated {len(ops)} "
                f"operations, expected {expected}"
            )
        _operations_cache[point_group] = xp.asarray(ops)

    return _operations_cache[point_group]


def symmetrize(
    tensor, operations, time_reversals=None, axial_axes=(), time_reversal_odd=False
):
    r"""Group-average a Cartesian tensor of any rank (Neumann's principle).

    Projects `tensor` onto the subspace invariant under every operation,
    i.e. the physically allowed form for a property tensor of a crystal
    with those (magnetic) point-group operations.

    `axial_axes` marks tensor axes that are pseudovector/axial legs
    (e.g. a magnetic-field index): each contributes an extra
    :math:`\det(R)` sign under an operation `R`. `time_reversal_odd`
    marks the tensor itself as odd under time reversal (e.g. it couples
    to magnetization linearly rather than quadratically): operations
    flagged anti-time-reversal in `time_reversals` (spglib convention:
    1 = anti-time-reversal) then contribute with a sign flip.
    """
    if time_reversals is None:
        time_reversals = xp.zeros(len(operations))

    total = xp.zeros_like(tensor)
    for op, reversed_ in zip(operations, time_reversals):
        rotated = tensor
        for axis in range(tensor.ndim):
            rotated = xp.moveaxis(
                xp.tensordot(op, rotated, axes=([1], [axis])), 0, axis
            )
        sign = 1.0
        if axial_axes:
            sign *= float(xp.linalg.det(op)) ** len(axial_axes)
        if time_reversal_odd and reversed_:
            sign *= -1.0
        total = total + sign * rotated
    return total / len(operations)


_CRYSTAL_SYSTEM_LATTICE = {
    "triclinic": np.eye(3),
    "monoclinic": np.eye(3),
    "orthorhombic": np.eye(3),
    "tetragonal": np.eye(3),
    "cubic": np.eye(3),
    "trigonal": np.array(
        [[1.0, -0.5, 0.0], [0.0, 3**0.5 / 2, 0.0], [0.0, 0.0, 1.0]]
    ),
    "hexagonal": np.array(
        [[1.0, -0.5, 0.0], [0.0, 3**0.5 / 2, 0.0], [0.0, 0.0, 1.0]]
    ),
}
"""Idealized (unit-length) lattice per crystal system, columns = a, b, c.

Only axis *directions/angles* matter for converting a fractional point
operation to Cartesian, not the actual cell lengths, so idealized cells
give exact results.
"""


def _crystal_system(spacegroup_number):
    if spacegroup_number <= 2:
        return "triclinic"
    if spacegroup_number <= 15:
        return "monoclinic"
    if spacegroup_number <= 74:
        return "orthorhombic"
    if spacegroup_number <= 142:
        return "tetragonal"
    if spacegroup_number <= 167:
        return "trigonal"
    if spacegroup_number <= 194:
        return "hexagonal"
    return "cubic"


_magnetic_operations_cache = {}


def magnetic_point_group_operations(uni_number, tol=1e-6):
    """(n, 3, 3) Cartesian ops + (n,) time-reversal flags for the magnetic
    point group underlying spglib magnetic-space-group database entry
    `uni_number` (1..1651), reduced to distinct (rotation, time-reversal)
    pairs -- i.e. translations are dropped, which is all Neumann's
    principle for a macroscopic property tensor ever sees.

    Time-reversal flags follow spglib: 1 marks an anti-time-reversal
    ("primed") operation. Look up `uni_number` via
    `spglib.get_magnetic_spacegroup_type` (BNS/OG/Litvin numbering) or
    `list_magnetic_point_groups`.
    """
    if uni_number in _magnetic_operations_cache:
        return _magnetic_operations_cache[uni_number]

    info = spglib.get_magnetic_spacegroup_type(uni_number)
    if info is None:
        raise ValueError(f"unrecognized magnetic uni_number: {uni_number!r}")
    data = spglib.get_magnetic_symmetry_from_database(uni_number)

    lattice = _CRYSTAL_SYSTEM_LATTICE[_crystal_system(info.number)]
    inv_lattice = np.linalg.inv(lattice)

    ops, flags = [], []
    for r_frac, reversed_ in zip(data["rotations"], data["time_reversals"]):
        r_cart = lattice @ r_frac @ inv_lattice
        if not any(
            f == reversed_ and np.allclose(o, r_cart, atol=tol)
            for o, f in zip(ops, flags)
        ):
            ops.append(r_cart)
            flags.append(reversed_)

    result = (
        xp.asarray(np.stack(ops)),
        xp.asarray(np.asarray(flags, dtype=float)),
    )
    _magnetic_operations_cache[uni_number] = result
    return result


def list_magnetic_point_groups(point_group):
    """Magnetic point groups whose unprimed operations are `point_group`.

    Scans all 1651 spglib magnetic-space-group database entries and
    returns, for each whose rotation set (ignoring time reversal)
    matches `point_group_operations(point_group)`, a dict with
    `uni_number`, `bns_number`, and `type` (1=colorless/ordinary,
    2=grey, 3=black-white, 4=translation-doubled -- see
    `magnetic_point_group_operations`).
    """
    target = point_group_operations(point_group)
    matches = []
    for uni_number in range(1, 1652):
        ops, _ = magnetic_point_group_operations(uni_number)
        distinct = []
        for op in ops:
            if not any(np.allclose(op, d, atol=1e-6) for d in distinct):
                distinct.append(op)
        if len(distinct) != len(target):
            continue
        if all(
            any(np.allclose(op, t, atol=1e-6) for t in target) for op in distinct
        ):
            info = spglib.get_magnetic_spacegroup_type(uni_number)
            matches.append(
                {
                    "uni_number": uni_number,
                    "bns_number": info.bns_number,
                    "type": info.type,
                }
            )
    return matches
